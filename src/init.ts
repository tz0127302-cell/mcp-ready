import { mkdir, readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { DISCLAIMER } from "./disclaimer.js";
import { discover } from "./discover.js";
import { McpReadyError } from "./errors.js";
import { toServerName, toToolName } from "./names.js";
import { loadSpec } from "./openapi/parse.js";
import { isCatchAllPath, isGenericAction, operationProse } from "./openapi/shape.js";
import type { Operation, ParsedSpec } from "./openapi/types.js";
import type { InitOptions, InitResult } from "./types.js";

export async function initProject(options: InitOptions): Promise<InitResult> {
  const resolved = path.resolve(options.target);
  let fileStat;
  try {
    fileStat = await stat(resolved);
  } catch {
    throw new McpReadyError(`Path not found: ${options.target}`);
  }
  const root = fileStat.isDirectory() ? resolved : path.dirname(resolved);
  await mkdir(root, { recursive: true });

  const discovery = await discover({
    root,
    recursive: true,
    ...(fileStat.isFile() && isOpenApiName(resolved) ? { specFile: resolved } : {}),
  });
  const spec = await loadPrimarySpec(root, discovery.openapiFiles, fileStat.isFile() ? resolved : undefined);
  const name = options.name?.trim() || spec?.info.title || (await packageName(root)) || path.basename(root);
  const description = firstSentence(options.description || spec?.info.description || `${name} HTTP API.`);
  const url = options.url || spec?.servers[0]?.url;
  const tools = spec ? suggestTools(spec) : [];

  const files: Record<string, string> = {
    "llms.txt": llmsTxt({ name, description, url, specPath: spec ? path.relative(root, spec.sourcePath) : undefined, tools }),
    "mcp.manifest.json": manifest({ name, description, tools }),
    "AGENTS.md": agentsMd({ name, description, tools }),
  };

  const written: string[] = [];
  const skipped: string[] = [];
  for (const [fileName, contents] of Object.entries(files)) {
    const full = path.join(root, fileName);
    const exists = await fileExists(full);
    if (exists && !options.force) {
      skipped.push(fileName);
      continue;
    }
    await writeFile(full, contents);
    written.push(fileName);
  }
  if (written.length === 0) {
    throw new McpReadyError(
      `llms.txt, mcp.manifest.json, and AGENTS.md already exist in ${root}. Pass --force to overwrite them.`,
    );
  }
  return { target: root, written, skipped, suggestedTools: tools.length };
}

async function loadPrimarySpec(
  root: string,
  files: string[],
  explicit?: string,
): Promise<ParsedSpec | undefined> {
  const ranked = [...files].sort((a, b) => rankSpec(a) - rankSpec(b) || a.length - b.length || a.localeCompare(b));
  const candidate = explicit && isOpenApiName(explicit) ? explicit : ranked[0] ? path.join(root, ranked[0]) : undefined;
  if (!candidate) return undefined;
  try {
    return await loadSpec(candidate);
  } catch {
    return undefined;
  }
}

function suggestTools(spec: ParsedSpec): { name: string; method: string; path: string; description: string }[] {
  return spec.operations
    .filter((operation) => !operation.deprecated && !isCatchAllPath(operation.path) && !isGenericAction(operation))
    .slice(0, 24)
    .map((operation) => ({
      name: toToolName(operation.operationId ?? synthesize(operation)),
      method: operation.method.toUpperCase(),
      path: operation.path,
      description: operationProse(operation) || `${operation.method.toUpperCase()} ${operation.path}`,
    }));
}

function synthesize(operation: Operation): string {
  return `${operation.method}_${operation.path.replace(/[^A-Za-z0-9]+/g, "_")}`.replace(/_+/g, "_");
}

function llmsTxt(input: {
  name: string;
  description: string;
  url?: string;
  specPath?: string;
  tools: { name: string; description: string }[];
}): string {
  const lines = [
    `# ${input.name}`,
    "",
    `> ${input.description}`,
    "",
    "Generated by mcp-ready as a starter index for coding agents. Edit the links so they point at documents a model can fetch.",
    "",
    DISCLAIMER,
    "",
    "## Docs",
    "",
  ];
  if (input.specPath) {
    lines.push(`- [OpenAPI specification](${link(input.specPath)}): Machine-readable contract. Prefer this over HTML docs.`);
  }
  lines.push("- [README](README.md): Human overview of the service.");
  if (input.url) lines.push(`- [API origin](${input.url}): Documented server URL. Confirm it before sending credentials.`);
  lines.push("");
  if (input.tools.length > 0) {
    lines.push("## Operations");
    lines.push("");
    for (const tool of input.tools.slice(0, 12)) {
      const href = input.specPath ? link(input.specPath) : "README.md";
      lines.push(`- [${tool.name}](${href}): ${oneLine(tool.description)}`);
    }
    lines.push("");
  }
  lines.push("## Optional");
  lines.push("");
  lines.push("- [AGENTS.md](AGENTS.md): When to call read tools versus mutating tools.");
  lines.push("- [MCP manifest](mcp.manifest.json): Starter description of a stdio MCP server. Generate the server with `mcp-ready generate`.");
  lines.push("");
  return `${lines.join("\n")}\n`;
}

function manifest(input: {
  name: string;
  description: string;
  tools: { name: string; method: string; path: string; description: string }[];
}): string {
  return `${JSON.stringify(
    {
      name: toServerName(input.name),
      version: "0.1.0",
      generatedBy: "mcp-ready",
      unofficial: true,
      disclaimer: DISCLAIMER,
      transport: { type: "stdio", command: "npm start" },
      instructions: `${input.description} Confirm auth and side effects before calling write tools. Mock servers generated by mcp-ready do not need credentials.`,
      tools: input.tools.map((tool) => ({
        name: tool.name,
        description: oneLine(tool.description),
        method: tool.method,
        path: tool.path,
      })),
    },
    null,
    2,
  )}\n`;
}

function agentsMd(input: {
  name: string;
  description: string;
  tools: { name: string; method: string; path: string; description: string }[];
}): string {
  const reads = input.tools.filter((tool) => tool.method === "GET" || tool.method === "HEAD");
  const writes = input.tools.filter((tool) => tool.method !== "GET" && tool.method !== "HEAD");
  const lines = [
    `# Agent skill hint: ${input.name}`,
    "",
    input.description,
    "",
    DISCLAIMER,
    "",
    "## When to use tools",
    "",
    reads.length
      ? `Read state with ${reads.map((tool) => `\`${tool.name}\``).join(", ")} before you change anything.`
      : "Prefer read operations before any write.",
    writes.length
      ? `Write tools: ${writes.map((tool) => `\`${tool.name}\` (${tool.method} ${tool.path})`).join(", ")}. Ask the user before calling them.`
      : "Do not invent write tools that are not listed.",
    "",
    "## Conventions",
    "",
    "- Send `Idempotency-Key` on creates, and reuse it when you retry.",
    "- Page with `cursor` until `nextCursor` is null. Do not assume a single page is the full collection.",
    "- On HTTP 401, refresh the credential. On 403, stop and tell the user. On 429, wait for `Retry-After`.",
    "- Do not call catch-all or admin execute endpoints. One tool should do one thing.",
    "- A server generated by mcp-ready starts in mock mode and returns fixtures until `MCP_READY_MOCK=0`.",
    "",
  ];
  return `${lines.join("\n")}\n`;
}

function link(specPath: string): string {
  return specPath.split(path.sep).join("/");
}

function oneLine(value: string): string {
  const line = value.replace(/\s+/g, " ").trim();
  return line.length > 180 ? `${line.slice(0, 177)}...` : line;
}

function firstSentence(value: string): string {
  const trimmed = value.replace(/\s+/g, " ").trim();
  const match = /^(.{1,220}?[.!?])(?:\s|$)/.exec(trimmed);
  return match?.[1] ?? trimmed.slice(0, 220);
}

async function packageName(root: string): Promise<string | undefined> {
  try {
    const raw = await readFile(path.join(root, "package.json"), "utf8");
    const parsed = JSON.parse(raw) as { name?: string };
    return typeof parsed.name === "string" ? parsed.name : undefined;
  } catch {
    return undefined;
  }
}

async function fileExists(file: string): Promise<boolean> {
  try {
    const info = await stat(file);
    return info.isFile();
  } catch {
    return false;
  }
}

function rankSpec(rel: string): number {
  const base = path.basename(rel).toLowerCase();
  if (base === "openapi.yaml" || base === "openapi.yml") return 0;
  if (base === "openapi.json") return 1;
  if (base.includes("openapi")) return 2;
  if (base.includes("swagger")) return 3;
  return 4;
}

function isOpenApiName(file: string): boolean {
  const ext = path.extname(file).toLowerCase();
  return ext === ".yaml" || ext === ".yml" || ext === ".json";
}
